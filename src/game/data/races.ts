function seg(
  partial: Omit<TerrainSegment, "night" | "aidAtEnd"> &
    Partial<Pick<TerrainSegment, "night" | "aidAtEnd">>,
): TerrainSegment {
  return {
    ...partial,
    night: partial.night ?? false,
    aidAtEnd: partial.aidAtEnd ?? false,
  };
}

